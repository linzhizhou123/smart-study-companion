def _parse_point_list(text: str) -> list[dict[str, Any]]:
    return parse_question_points(text)


def _question_difficulty(row: dict[str, Any]) -> int:
    score = float(row.get("满分_num") or row.get("满分") or 1)
    if score >= 3:
        return 3
    if str(row.get("题型", "")) in {"解答题", "选择题"}:
        return 2
    return 1


def build_knowledge_graph(dfs: dict[str, Any]) -> dict[str, Any]:
    course = dfs["course_requirements"]
    questions = dfs["questions"]
    nodes = dfs["nodes"]

    # 主题
    themes: dict[str, dict[str, Any]] = {}
    for _, row in course.iterrows():
        tid = row["主题编号"]
        if tid not in themes:
            materials = THEME_MATERIALS.get(tid, {})
            themes[tid] = {
                "主题编号": tid,
                "主题名称": row["主题"],
                "主题目标": row["主题目标"],
                "教材位置": [materials.get("教材页码范围", row["教材正文页"]), materials.get("教材", "")],
                "教材名称": materials.get("教材名称", ""),
                "前置主题": THEME_PREREQUISITES.get(tid, []),
                "课标引用": {"编号": row["课标整理编号"], "PDF页／印刷页": row["课标文件页／正文页"]},
                "指标列表": [],
            }

    # 指标
    indicators: dict[str, dict[str, Any]] = {}
    for _, row in course.iterrows():
        tid = row["主题编号"]
        iid = row["指标编号"]
        materials = THEME_MATERIALS.get(tid, {})
        indicators[iid] = {
            "指标编号": iid,
            "主题编号": tid,
            "观察指标": row["观察指标"],
            "课标引用": {
                "编号": row["课标整理编号"],
                "PDF页／印刷页": row["课标文件页／正文页"],
            },
            "教材页码": [materials.get("教材页码范围", row["教材正文页"]), materials.get("教材", "")],
            "前置指标": INDICATOR_PREREQUISITES.get(iid, []),
            "学习卡": materials.get("学习卡", ""),
            "教材": materials.get("教材", ""),
            "题目列表": [],
            "题目详情": [],
        }

    # 题目详情
    question_lookup: dict[str, dict[str, Any]] = {}
    available_nodes: dict[str, list[str]] = {qid: [] for qid in questions["材料编号"]}
    for _, node in nodes.iterrows():
        for qid in node["可用题目列表"]:
            available_nodes.setdefault(qid, []).append(node["节点编号"])

    for _, row in questions.iterrows():
        if row.get("材料类型") != "题目":
            continue
        qid = row["材料编号"]
        iid = str(row.get("指标编号", "")).strip()
        tid = str(row.get("主题编号", "")).strip()
        point_list = []
        for point in row.get("评分点列表", []) or []:
            pid = point["编号"]
            tag_id = SCORE_POINT_TAGS.get(pid)
            tag = KNOWLEDGE_TAGS.get(tag_id, {}) if tag_id else {}
            point_list.append(
                {
                    "编号": pid,
                    "描述": point["描述"],
                    "满分": point["满分"],
                    "知识点编号": tag_id or "",
                    "知识点": tag.get("名称", "未标注"),
                }
            )
        tags = sorted({p["知识点编号"] for p in point_list if p["知识点编号"]})
        detail = {
            "编号": qid,
            "材料类型": "题目",
            "题型": row.get("题型", ""),
            "主题编号": tid,
            "指标编号": iid,
            "题干": row.get("题干或内容", ""),
            "选项": row.get("选项", ""),
            "满分": float(row.get("满分_num") or row.get("满分") or 1),
            "参考答案": row.get("参考答案", ""),
            "参考解析": row.get("参考解析", ""),
            "评分点": point_list,
            "知识点编号": tags,
            "知识点": [KNOWLEDGE_TAGS[t]["名称"] for t in tags],
            "教材定位": TAG_TEXTBOOK_NOTES.get(tags[0], "") if tags else "",
            "来源": row.get("来源或资料文件", ""),
            "可用节点": sorted(available_nodes.get(qid, [])),
            "难度": _question_difficulty(row),
            "是否解答题": row.get("题型") == "解答题",
        }
        question_lookup[qid] = detail
        if iid in indicators:
            indicators[iid]["题目列表"].append(qid)
            indicators[iid]["题目详情"].append(detail)

    # 组装主题→指标
    for _, row in course.iterrows():
        tid = row["主题编号"]
        iid = row["指标编号"]
        if tid in themes and iid in indicators:
            themes[tid]["指标列表"].append(indicators[iid])

    # 学习卡与教材材料
    materials = []
    for _, row in questions.iterrows():
        if row.get("材料类型") == "题目":
            continue
        materials.append(
            {
                "材料编号": row["材料编号"],
                "材料类型": row.get("材料类型", ""),
                "题干或内容": row.get("题干或内容", ""),
                "指标编号": row.get("指标编号", ""),
                "来源": row.get("来源或资料文件", ""),
            }
        )

    # 知识点索引
    tag_index: dict[str, dict[str, Any]] = {}
    for tag_id, meta in KNOWLEDGE_TAGS.items():
        related_points = [pid for pid, t in SCORE_POINT_TAGS.items() if t == tag_id]
        related_questions = sorted({pid[:4] for pid in related_points})
        related_indicators = sorted(
            {indicators[iid]["指标编号"] for iid in indicators if any(q in indicators[iid]["题目列表"] for q in related_questions)}
        )
        tag_index[tag_id] = {
            "编号": tag_id,
            "名称": meta["名称"],
            "说明": meta["说明"],
            "主题编号": meta["主题"],
            "指标编号": related_indicators,
            "评分点": related_points,
            "题目": related_questions,
            "被考核次数": len(related_points),
            "教材定位": TAG_TEXTBOOK_NOTES.get(tag_id, ""),
        }

    # 校验映射完整性
    all_point_ids = set(dfs["point_meta"].keys())
    mapped = set(SCORE_POINT_TAGS.keys())
    missing = sorted(all_point_ids - mapped)
    extra = sorted(mapped - all_point_ids)
    if missing or extra:
        raise ValueError(f"评分点映射不完整：缺少 {missing}；多余 {extra}")

    # 按主题输出
    theme_list = []
    for tid in ("T01", "T02", "T03"):
        if tid in themes:
            theme_list.append(themes[tid])

    return {
        "数据版本": "ZHIHUI-XUEBAN-20261110",
        "主题列表": theme_list,
        "指标索引": indicators,
        "题库": question_lookup,
        "材料": materials,
        "评分点→知识点": SCORE_POINT_TAGS,
        "知识点索引": tag_index,
        "前置关系": {
            "指标": INDICATOR_PREREQUISITES,
            "主题": THEME_PREREQUISITES,
        },
        "必要联系": REQUIRED_CONNECTIONS,
        "教材索引": THEME_MATERIALS,
    }
